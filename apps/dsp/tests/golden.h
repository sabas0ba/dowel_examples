/* 期待値。**この1枚をすべての三つ組が読む。**
 *
 * ホスト向けの検査（tests/vectors.c）も、ベアメタルの検査
 * （fw/src/onhw.c）も、ここに書いた同じ数と突き合わせる。三つ組ごとに
 * 別の期待値を持つと、「機械が違えば答も違う」を検査が追認してしまう。
 * 整数だけで書いた算法にその逃げ道を与えない。
 *
 * 値は算法を最初に書いたときにホストで測り、ここに焼いた。以後これは
 * 仕様であって観測ではない——ホストで変わったなら、それは退行である。 */
#ifndef DSP_GOLDEN_H
#define DSP_GOLDEN_H

/* 試験波の長さ。ベアメタル側の stack にも載る大きさにしてある。 */
#define GOLDEN_N 256

/* 入力そのものの畳み込み。算法に入る前の段が揃っていることを見る。
 * ここが違えば、フィルタではなく波の生成が三つ組で違っている。 */
#define GOLDEN_IN_CRC   0x53106E76u

/* 通したあとの畳み込み。1標本でも違えば違う値になる。 */
#define GOLDEN_OUT_CRC  0xB9B26EF1u

/* 振れ幅の総和。入力より出力の方が小さいこと（平滑化が効いたこと）を、
 * 畳み込みとは別の筋で見る。CRC は「違う」しか言わないので、
 * **どちらへ違うのか**を見る量を1つ持っておく。ここでは 13.6 倍滑らかに
 * なる。 */
#define GOLDEN_IN_ROUGH   1342514u
#define GOLDEN_OUT_ROUGH  98452u

/* 全振幅の交番を通したときの出力の上限。低域通過に最も速い波を入れる
 * ので、出力は小さく収まる（実測 1054）。中間の積を 32 ビットで持つと
 * ここが溢れて暴れるので、桁あふれの見張りとして置いてある。 */
#define GOLDEN_SAT_PEAK 1200

#endif
